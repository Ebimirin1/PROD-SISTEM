-- 4. Grava os resumos semanais (reexecutar só atualiza)
insert into public.sales_records (sale_type, customer, sale_number, item_seq, sale_date, product_code, product_name, qty, total)
select 'VAREJO', 'PLANILHA PEDIDO FÁBRICA (semana)', 'PLAN-' || p.wk, p.code::int, p.wk, p.code,
       coalesce(c.product_name, p.code), p.qty, 0
from plan_weeks p
left join public.product_catalog c on c.product_code = p.code
on conflict (sale_type, sale_number, item_seq)
do update set qty = excluded.qty, product_name = excluded.product_name, sale_date = excluded.sale_date, imported_at = now();

commit;

notify pgrst, 'reload schema';
