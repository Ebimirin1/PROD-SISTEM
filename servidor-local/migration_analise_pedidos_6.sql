-- Cada linha vira uma venda "resumo da semana" (sale_number 'PLAN-<segunda>', cliente 'PLANILHA PEDIDO FÁBRICA'),
-- com data na segunda-feira da semana. Quando o relatório de verdade dessa semana for importado,
-- o gatilho apaga os resumos da semana (não soma em dobro).
-- Pode rodar mais de uma vez. FAÇA BACKUP ANTES.
begin;

-- 1. Gatilho: importação de vendas reais apaga os resumos da planilha das mesmas semanas
create or replace function public.sales_records_drop_plan_weeks()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  delete from public.sales_records p
  using (select distinct n.sale_type, date_trunc('week', n.sale_date)::date as wk
           from new_rows n where n.sale_number not like 'PLAN-%') x
  where p.sale_number like 'PLAN-%' and p.sale_type = x.sale_type and p.sale_date = x.wk;
  return null;
end $$;

drop trigger if exists sales_records_drop_plan_weeks on public.sales_records;
create trigger sales_records_drop_plan_weeks
  after insert on public.sales_records
  referencing new table as new_rows
  for each statement execute function public.sales_records_drop_plan_weeks();

